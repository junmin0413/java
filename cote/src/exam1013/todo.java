package exam1013;

public class todo {
	public String task;
	public String OX;
	
	public todo() {}
	public todo(String task, String OX) {
		this.task = task;
		this.OX = OX;
	}
	
	public String getTask() {
		return task;
	}
	public void setTask(String task) {
		this.task = task;
	}
	public String getOX() {
		return OX;
	}
	public void setOX(String oX) {
		OX = oX;
	}
	
}
